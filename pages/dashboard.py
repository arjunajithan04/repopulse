def _fmt(value: int | float) -> str:
    value = value or 0
    if value >= 1_000_000:
        return f"{value / 1_000_000:.1f}M"
    if value >= 1_000:
        return f"{value / 1_000:.1f}K"
    return f"{value:,}"


def _delta(current, previous, inverse=False):
    if previous is None or previous == 0:
        return None
    change = ((current - previous) / abs(previous)) * 100
    good = change <= 0 if inverse else change >= 0
    sign = "+" if change > 0 else ""
    return f"{sign}{change:.1f}%", "good" if good else "bad"


def _health_status(score: float):
    if score >= 80:
        return "HEALTHY", "good"
    if score >= 60:
        return "MODERATE", "warning"
    return "AT RISK", "danger"


def _history_frame(repo_name: str) -> pd.DataFrame:
    snapshots = list(reversed(get_snapshots(repo_name, limit=30)))
    return pd.DataFrame(snapshots) if snapshots else pd.DataFrame()


def _current_snapshot(analysis) -> dict:
    metrics = analysis.metrics or {}
    return {
        "stars": analysis.repository.stars,
        "forks": analysis.repository.forks,
        "issues": metrics.get("open_issue_count", 0),
        "pull_requests": metrics.get("open_pull_request_count", 0),
        "contributors": metrics.get("total_contributors", 0),
        "commits": metrics.get("recent_commit_count", 0),
        "health": metrics.get("repository_health_score", 0),
    }


def _render_what_changed(analysis, previous):
    section_header("What changed", "The strongest movements since the previous stored snapshot.", "Delta intelligence")
    if not previous:
        st.info("This is the first comparison point. Re-scan the repository later to unlock change intelligence.")
        return
    trends = trend_summary(_current_snapshot(analysis), previous)
    changed = [t for t in trends if t["change"] != 0]
    if not changed:
        st.success("No measured metrics changed since the previous scan.")
        return
    for t in changed:
        symbol = "↑" if t["direction"] == "up" else "↓"
        cls = "positive" if t["interpretation"] == "improved" else "negative"
        pct = f"{t['pct']:+.1f}%" if t["pct"] is not None else "new"
        st.html(
            f'<div class="change-row"><span class="change-symbol {cls}">{symbol}</span><strong>{html.escape(t["label"])}</strong><span>{t["previous"]:,.1f} → {t["current"]:,.1f} · {pct}</span></div>'
        )


def _render_history(repo_name: str):
    df = _history_frame(repo_name)
    if df.empty:
        st.info("No persistent history yet. Analyze this repository again later to build trends.")
        return

    section_header("Live history", "Every analysis creates a timestamped snapshot that feeds the trend layer.", "Historical telemetry")
    chart_df = df.copy()
    chart_df["captured_at"] = pd.to_datetime(chart_df["captured_at"], errors="coerce")
    metric_options = {
        "Health score": "health_score",
        "Recent commits": "recent_commits",
        "Open issues": "open_issues",
        "Open pull requests": "open_pull_requests",
        "Contributors": "contributors",
        "Stars": "stars",
        "Forks": "forks",
        "Engineering": "engineering_score",
    }
    selected = st.selectbox("Historical metric", list(metric_options), key="phase2_history_metric", label_visibility="collapsed")
    render_history_chart(chart_df, metric_options[selected], selected, height=340)
    st.caption("Hover points to inspect individual snapshots. The chart uses the persistent SQLite history generated by previous repository scans.")


def _render_scorecard(analysis, history_df: pd.DataFrame, risks, assessment_result):
    """Render the executive 10-second repository scorecard."""
    scorecard = build_scorecard(analysis.metrics or {}, history_df.to_dict("records") if not history_df.empty else [])
    section_header("Repository scorecard", "The fastest read on how the repository is doing right now.", "Executive signal")

    cards = scorecard["cards"]
    labels = ["Health", "Activity", "Community", "Stability", "Momentum"]
    cols = st.columns(5)
    for col, label in zip(cols, labels):
        with col:
            tone = scorecard["tones"][label]
            st.html(
                f'<div class="scorecard-metric {tone}">'
                f'<div class="scorecard-metric-label">{html.escape(label)}</div>'
                f'<div class="scorecard-metric-value">{cards[label]:.0f}<span>/100</span></div>'
                f'<div class="scorecard-track"><span style="width:{cards[label]:.1f}%"></span></div>'
                f'</div>'
            )

    strongest = scorecard["strongest_dimension"]
    weakest = scorecard["weakest_dimension"]
    risk_count = len(risks or [])
    primary_action = (assessment_result.get("priorities") or [None])[0] if assessment_result else None
    if not primary_action:
        primary_action = f"Focus on improving {weakest.lower()} to strengthen the repository's next score."

    left, right = st.columns([1.05, 1], vertical_alignment="top")
    with left:
        st.html(
            f'<div class="scorecard-status {scorecard["tone"]}">'
            f'<div class="scorecard-status-kicker">Current state</div>'
            f'<div class="scorecard-status-title">{html.escape(scorecard["status"])}</div>'
            f'<div class="scorecard-status-copy">Strongest signal: <strong>{html.escape(str(strongest))}</strong>. '
            f'Weakest signal: <strong>{html.escape(weakest)}</strong>.</div>'
            f'</div>'
        )
    with right:
        st.html(
            f'<div class="scorecard-action">'
            f'<div class="scorecard-action-kicker">Next best action</div>'
            f'<div class="scorecard-action-title">{html.escape(str(primary_action))}</div>'
            f'<div class="scorecard-action-copy">{risk_count} active risk signal{"s" if risk_count != 1 else ""} · {html.escape(scorecard["momentum_note"])}</div>'
            f'</div>'
        )


