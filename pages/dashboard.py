def _render_timeline_moments(df: pd.DataFrame):
    """Render explainable repository milestones from persisted snapshots."""
    snapshots = df.to_dict("records") if not df.empty else []
    summary = timeline_summary(snapshots)

    if summary["status"] == "insufficient":
        st.caption(summary["headline"])
        return

    st.html(
        f'<div class="timeline-summary"><span class="timeline-summary-kicker">Repository story</span>'
        f'<strong>{html.escape(summary["headline"])}</strong>'
        f'<span>{summary["snapshot_count"]} stored scans · {len(summary["events"])} meaningful milestones detected</span></div>'
    )

    events = summary["events"]
    if not events:
        st.caption("No major shifts crossed the milestone thresholds. The repository has remained comparatively stable.")
        return

    st.markdown('<div class="timeline-moments">', unsafe_allow_html=True)
    for event in events[:6]:
        try:
            date_value = pd.to_datetime(event["date"], errors="coerce")
            date_text = date_value.strftime("%d %b %Y") if pd.notna(date_value) else "Stored scan"
        except Exception:
            date_text = "Stored scan"
        severity = event.get("severity", "info")
        icon = "↑" if severity == "positive" else "↓" if severity == "negative" else "•"
        card = (
            f'<div class="timeline-moment {html.escape(severity)}">'
            f'<div class="timeline-moment-dot">{icon}</div>'
            f'<div class="timeline-moment-body">'
            f'<div class="timeline-moment-meta">{html.escape(date_text)} · Health {float(event.get("health", 0)):.1f}</div>'
            f'<strong>{html.escape(event["title"])}</strong>'
            f'<span>{html.escape(event["detail"])}</span>'
            f'</div></div>'
        )
        st.html(card)
    st.markdown('</div>', unsafe_allow_html=True)


def dashboard_page():
    analysis = st.session_state.get("repo_analysis")
    if analysis is None:
        page_header("Workspace", "Repository intelligence", "Connect a GitHub repository to turn raw activity into a clear health and risk picture.")
        empty_state("Your command center is waiting", "Analyze a repository from the Repository page. Once data is loaded, this view becomes your live health, trend and risk workspace.", "◈")
        return

    repo = analysis.repository
    metrics = analysis.metrics or {}
    previous = st.session_state.get("previous_snapshot") or {}
    score = float(metrics.get("repository_health_score", 0) or 0)
    status, tone = _health_status(score)
    result = assessment(metrics, previous)
    risks = detect_risks(metrics)

    page_header("Live repository", "Repository command center", f"{repo.full_name} · scanned from GitHub telemetry")
    _render_repo_hero(repo, score, status, tone, previous)

    delta_score = score - float(previous.get("health", score)) if previous else None
    risk_count = len(risks)
    render_telemetry_strip([
        ("Health", f"{score:.1f}", tone),
        ("Risk signals", str(risk_count), "danger" if risk_count >= 3 else "warning" if risk_count else "good"),
        ("Session scans", f"{st.session_state.get('repo_session_count', 0)}/10", "neutral"),
        ("Telemetry", "LIVE", "good"),
    ])

    orb_col, spotlight_col = st.columns([.85, 1.15])
    with orb_col:
        render_health_orb(score, status, delta_score)
    with spotlight_col:
        spotlight_tone = "danger" if any(r.severity in {"Critical", "High"} for r in risks) else "warning" if risks else "good"
        render_spotlight(
            result["weakest_dimension"],
            result["intro"],
            f"{risk_count} risk signal{'s' if risk_count != 1 else ''} detected · {result['priorities'][0] if result['priorities'] else 'No priority action required.'}",
            spotlight_tone,
            "Current intelligence spotlight",
        )

    cards = [
        ("Stars", _fmt(repo.stars), _delta(repo.stars, previous.get("stars")), "GitHub popularity", "★"),
        ("Forks", _fmt(repo.forks), _delta(repo.forks, previous.get("forks")), "Repository copies", "⑂"),
        ("Open issues", _fmt(metrics.get("open_issue_count", 0)), _delta(metrics.get("open_issue_count", 0), previous.get("issues"), True), "Lower backlog is healthier", "!"),
        ("Open PRs", _fmt(metrics.get("open_pull_request_count", 0)), _delta(metrics.get("open_pull_request_count", 0), previous.get("pull_requests"), True), "Lower backlog is healthier", "↗"),
    ]
    cols = st.columns(4)
    for col, (title, value, delta, help_text, icon) in zip(cols, cards):
        with col:
            metric_card(title, value, delta[0] if delta else None, help_text, delta[1] if delta else "neutral", icon=icon)

    section_header("Repository pulse", "The six dimensions behind the current health signal.", "Command center")
    pulse_left, pulse_right = st.columns([1.2, 1])
    with pulse_left:
        dimensions = metrics.get("health_dimensions", {}) or {}
        if dimensions:
            render_health_radar(dimensions, height=300)
            for name, dimension_score in dimensions.items():
                health_dimension(str(name), float(dimension_score or 0))
        else:
            st.info("No health dimension data is available for this scan.")
    with pulse_right:
        if risks:
            for risk in risks[:3]:
                risk_cls = "danger" if risk.severity in {"Critical", "High"} else "warning"
                st.html(
                    f'<div class="mini-risk {risk_cls}"><span class="mini-risk-dot"></span><div><strong>{html.escape(risk.title)}</strong><span>{html.escape(risk.severity)}</span></div></div>'
                )
        else:
            st.success("No major risk signals detected from the current metrics.")

    _render_what_changed(analysis, previous)

    activity = metrics.get("activity_intelligence", {}) or {}
    engineering = metrics.get("engineering_intelligence", {}) or {}
    section_header("Engineering & activity pulse", "Recent development behaviour and engineering hygiene.", "Operational signal")
    p1, p2, p3, p4 = st.columns(4)
    with p1:
        metric_card("Activity", activity.get("status", "Unknown"), f"{activity.get('commit_trend_pct', 0):+.1f}% trend", "Recent commit direction", "good" if activity.get("commit_trend_pct", 0) >= 0 else "bad", "↗")
    with p2:
        engineering_score = float(engineering.get("engineering_score", 0) or 0)
        metric_card("Engineering", f"{engineering_score:.1f}", "Engineering hygiene", "Composite engineering score", "good" if engineering_score >= 80 else "bad", "⌘", progress=engineering_score)
    with p3:
        testing_score = float(engineering.get("testing_score", 0) or 0)
        metric_card("Testing", f"{testing_score:.1f}", "Test coverage signal", "Observed testing posture", "good" if testing_score >= 80 else "bad", "✓", progress=testing_score)
    with p4:
        documentation_score = float(engineering.get("documentation_score", 0) or 0)
        metric_card("Documentation", f"{documentation_score:.1f}", "Documentation signal", "README, license and contributor docs", "good" if documentation_score >= 80 else "bad", "▤", progress=documentation_score)
    st.caption(f"Last commit: {activity.get('last_commit_days_ago', 0)} days ago · {engineering.get('dependencies_observed', 0)} observed dependencies · {engineering.get('test_files', 0)} test files")

    c1, c2 = st.columns(2)
    with c1:
        section_header("Assessment", "A plain-language interpretation of the latest scan.")
        st.write(result["intro"])
        insight_card("Primary improvement area", f"{result['weakest_dimension']}. {result['priorities'][0]}", "warning", "Priority", "↳")
    with c2:
        section_header("Repository pulse", "The core numbers behind this scan.")
        r1, r2, r3 = st.columns(3)
        with r1:
            metric_card("Contributors", _fmt(metrics.get("total_contributors", 0)), help_text="Visible contributor volume", icon="◎")
        with r2:
            metric_card("Bus factor", _fmt(metrics.get("bus_factor", 0)), help_text="Contributor concentration signal", icon="⊙")
        with r3:
            metric_card("Recent commits", _fmt(metrics.get("recent_commit_count", 0)), help_text="Recent development activity", icon="↻")

    history_df = _history_frame(repo.full_name)
    _render_scorecard(analysis, history_df, risks, result)
    _render_resilience(analysis, history_df)
    if not history_df.empty:
        section_header("Repository timeline", "See how repository health and development momentum have evolved across every stored scan.", "Evolution intelligence")
        render_repository_health_timeline(history_df, height=430)
        _render_timeline_moments(history_df)

        section_header("Health trajectory", "A focused view of the health signal across stored scans.", "Historical telemetry")
        render_health_trajectory(history_df, height=300)
    _render_history(repo.full_name)
